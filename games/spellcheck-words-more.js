    function mergeInto(set, extra) {
        ['basic', 'advanced', 'expert', 'boss'].forEach(tier => {
            if (!extra[tier]) return;
            const have = new Set();
            ['basic', 'advanced', 'expert', 'boss'].forEach(t => (set[t] || []).forEach(e => have.add(e[0].toLowerCase())));
            set[tier] = (set[tier] || []).concat(extra[tier].filter(e => !have.has(e[0].toLowerCase())));
        });
    }
