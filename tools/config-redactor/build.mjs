import fs from 'node:fs';
import ts from '../../mcp-experiment/node_modules/typescript/lib/typescript.js';
const base = new URL('./', import.meta.url), out = new URL('../../nettools/config-redactor/', base);
function change(text, from, to) {
  if (!text.includes(from)) throw new Error('Upstream source changed: ' + from);
  return text.replace(from, to);
}
for (const name of ['types', 'scanner', 'cisco', 'profiles', 'vendors', 'addresses', 'replacements']) {
  let source = fs.readFileSync(new URL('vendor/' + name + '.ts', base), 'utf8');
  source = source.replace(/from '(\.\/[^']+)'/g, (_, name) => "from '" + name + ".js'").replaceAll("from 'node:net'", "from './runtime.js'");
  if (name === 'scanner' || name === 'cisco') source = change(source, 'Buffer.byteLength(source)', 'new TextEncoder().encode(source).byteLength');
  if (name === 'addresses') {
    source = change(source, "import {createHmac} from 'node:crypto';", '');
    source = change(source, 'export function mapAddresses(', 'export async function mapAddresses(');
    source = change(source, 'key: Buffer): Map<number,string | undefined>', 'key: Uint8Array): Promise<Map<number,string | undefined>>');
    source = change(source, '  const defaults =', "  const cryptoKey = await crypto.subtle.importKey('raw', key, {name:'HMAC',hash:'SHA-256'}, false, ['sign']);\n  const defaults =");
    const value = String.fromCharCode(96) + ['group.bits','group.base','group.prefix','attempt'].map(s => '$'+'{'+s+'}').join(':') + String.fromCharCode(96);
    source = change(source, "createHmac('sha256',key).update("+value+").digest('hex')",
      "Array.from(new Uint8Array(await crypto.subtle.sign('HMAC', cryptoKey, new TextEncoder().encode("+value+"))), b => b.toString(16).padStart(2,'0')).join('')");
  }
  if (name === 'replacements') {
    source = change(source, 'export function replace(', 'export async function replace(');
    source = change(source, 'key: Buffer}): Result', 'key: Uint8Array}): Promise<Result>');
    source = change(source, '? mapAddresses(', '? await mapAddresses(');
  }
  const result = ts.transpileModule(source, {compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.ES2022}});
  const destination = new URL(name + '.js', out);
  const output = '// Generated by tools/config-redactor/build.mjs. See LICENSE.txt.\n' + result.outputText;
  if (process.argv.includes('--check')) {
    if (fs.readFileSync(destination, 'utf8').replaceAll('\r\n','\n') !== output.replaceAll('\r\n','\n')) throw new Error('Rebuild browser module: ' + name);
  } else fs.writeFileSync(destination, output);
}
console.log('Built browser redactor.');
